/// Magic number used to identify a valid SFS filesystem.
/// Stored in the superblock for filesystem validation during mount.
const MAGIC_NUMBER: u32 = 0x_DEAD_BEEF;

/// Inode number for the root directory of the filesystem.
/// The root directory is always at inode 0 by convention.
const ROOT_DIRECTORY_INODE: u64 = 0;

