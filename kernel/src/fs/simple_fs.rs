//! Simple File System (SFS) implementation for creo.
//!
//! This module provides a basic Unix-like file system with the following features:
//! - Superblock-based metadata tracking
//! - Inode-based file representation with direct and indirect pointers
//! - Directory hierarchy with root directory at inode 0
//! - Bitmap-based allocation tracking for inodes and data blocks
//! - Support for file creation, deletion, reading, and writing
//! - Path-based file lookup with directory traversal
//!
//! # Disk Layout
//! ```text
//! Block 0: Superblock
//! Block 1: Inode Bitmap
//! Block 2: Data Block Bitmap
//! Block 3+: Inode Table (10% of disk capacity)
//! Remaining: Data Blocks (90% of disk capacity)
//! ```
//!
