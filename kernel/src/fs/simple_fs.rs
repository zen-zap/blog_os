	///   - `dir_block_buffer`: The entire directory block (for modification)
	///   - `dir_block_addr`: The absolute block address of the directory
	/// * `Err(FileError::Corrupt)` - If parent is not a directory or has no data block
	/// * `Err(FileError::FileNotFound)` - If filename not found in directory
	/// * `Err(FileError::BlockReadError)` - If block read fails
	///
	/// # Implementation Details
	/// - Reads the parent directory inode
	/// - Validates it's a directory type
	/// - Reads the directory's first data block
	/// - Scans entries for matching filename
	/// - Returns complete entry information
	fn find_entry_detailed(
		&mut self,
		parent_inode_num: u64,
		filename: &str,
	) -> Result<
		(
			usize,            /* slot index */
			u64,              /* file inode num */
			[u8; BLOCK_SIZE], /* parent dir block buffer */
			u64,              /* parent dir block address */
		),
		FileError,
	> {
		let parent_inode = self.read_inode(parent_inode_num).map_err(|_| FileError::Corrupt)?;
		if parent_inode.mode != FileType::Directory {
			return Err(FileError::Corrupt);
		}

		let dir_block_addr = parent_inode.direct_pointers[0];
		if dir_block_addr == 0 {
			return Err(FileError::FileNotFound);
		}

		let mut dir_block_buf = [0u8; BLOCK_SIZE];
		self.device
			.read_blocks(dir_block_addr, &mut dir_block_buf)
			.map_err(|_| FileError::BlockReadError)?;

		let entries = DirEntryBlock::new(&dir_block_buf);
		for (i, e) in entries.enumerate() {
			let used = (e.flags.get() & DIRENT_USED) != 0;
			if used {
				let nlen = e.name_len.get() as usize;
				if &e.name[..nlen] == filename.as_bytes() {
					// Found it!
					return Ok((i, e.inode.get(), dir_block_buf, dir_block_addr));
				}
			}
		}

		Err(FileError::FileNotFound)
	}

